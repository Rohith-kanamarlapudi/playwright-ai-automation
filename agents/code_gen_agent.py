    """
    Logs in ONCE per test session (only if EMAIL/PASSWORD are configured
    and the target actually presents a login form) and keeps the
    resulting context (cookies + localStorage + sessionStorage) alive
    for every test.
 
    Falls back to a plain, unauthenticated context when no credentials
    are set or login isn't applicable — e.g. the CI smoke test that
    points TARGET_URL at a public marketing site. This mirrors the
    original fixture's intent (auth if possible, plain context
    otherwise) without depending on a brittle static auth.json file.
    """
    context = browser.new_context()
 
    if EMAIL and PASSWORD:
        setup_page = context.new_page()
        try:
            _perform_login(setup_page)
            try:
                context.storage_state(path="auth.json")
            except Exception:
                pass
        except Exception as e:
            print(f"[conftest] Login skipped ({{e}}); using anonymous context.")
        finally:
            setup_page.close()
    else:
        print(
            "[conftest] EMAIL/PASSWORD not set — using an unauthenticated "
            "context. Set EMAIL and PASSWORD in .env if the target "
            "requires login."
        )
 
    yield context
    context.close()
 
 
